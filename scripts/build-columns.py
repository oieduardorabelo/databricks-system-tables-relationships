#!/usr/bin/env python3
"""Write columns.js from the export made by scripts/export-system-tables.sh.

columns.js keeps only public schema facts: table names, column names, column
types and the Databricks table descriptions. It leaves out workspace details
(metastore IDs, storage paths, owners).
Struct columns are flattened: usage_metadata.job_id is a row of its own.
Fields inside arrays and maps are not flattened.
"""
import datetime, glob, json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
export = os.path.join(here, ".uc-export")
target = os.path.join(here, "..", "columns.js")


def type_name(t):
    """Spark JSON type -> short SQL-like type text."""
    if isinstance(t, str):
        return t
    kind = t.get("type")
    if kind == "struct":
        return "struct"
    if kind == "array":
        return f"array<{type_name(t['elementType'])}>"
    if kind == "map":
        return f"map<{type_name(t['keyType'])}, {type_name(t['valueType'])}>"
    if kind == "udt":
        return type_name(t.get("sqlType", "udt"))
    return str(kind)


def flatten(prefix, t, rows):
    if isinstance(t, dict) and t.get("type") == "struct":
        for f in t["fields"]:
            path = f"{prefix}.{f['name']}"
            rows.append([path, type_name(f["type"])])
            flatten(path, f["type"], rows)


def clean_comment(text):
    if not text:
        return ""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)  # keep link text only
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= 400 else text[:397].rsplit(" ", 1)[0] + "…"


# information_schema describes data objects (catalogs, tables, privileges), not
# account activity, and the Databricks system tables list does not include it.
SKIP_SCHEMAS = {"information_schema"}

columns, comments, schemas = {}, {}, []
files = sorted(glob.glob(os.path.join(export, "*.json")))
if not files:
    sys.exit("No export found. Run scripts/export-system-tables.sh first.")
for f in files:
    schema = os.path.basename(f)[:-5]
    if schema in SKIP_SCHEMAS:
        continue
    tables = json.load(open(f))
    if tables:
        schemas.append(schema)
    for t in sorted(tables, key=lambda t: t["name"]):
        tid = f"system.{schema}.{t['name']}"
        rows = []
        for c in t.get("columns", []):
            tj = json.loads(c["type_json"]) if c.get("type_json") else {"type": c.get("type_name", "").lower()}
            ctype = tj.get("type")
            rows.append([c["name"], type_name(ctype) if isinstance(ctype, (dict, str)) else c["type_text"]])
            flatten(c["name"], ctype, rows)
        columns[tid] = rows
        if clean_comment(t.get("comment")):
            comments[tid] = clean_comment(t.get("comment"))

out = [
    "// Generated by scripts/build-columns.py from a Unity Catalog export. Do not edit by hand.",
    f"window.ERD_EXPORT = {json.dumps({'date': datetime.date.today().isoformat(), 'schemas': schemas})};",
    "window.ERD_COMMENTS = " + json.dumps(comments, indent=1, ensure_ascii=False) + ";",
    "window.ERD_COLUMNS = {",
]
for tid, rows in columns.items():
    out.append(f"  {json.dumps(tid)}: {json.dumps(rows, separators=(',', ':'))},")
out.append("};")
open(target, "w").write("\n".join(out) + "\n")
print(f"Wrote columns.js: {len(columns)} tables, {sum(len(r) for r in columns.values())} columns and struct fields.")
